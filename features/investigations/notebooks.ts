import type {
  ChatMessage,
  ChatSession,
  InvestigationItem,
  Repository,
  Workspace,
} from '../../types';
import { db } from '../../services/storage/db';

export function createInvestigationSession(repositoryId: string | null, title = 'New investigation', workspaceId?: string): ChatSession {
  const now = Date.now();
  return {
    id: `investigation:${crypto.randomUUID()}`,
    repositoryId,
    title,
    createdAt: now,
    updatedAt: now,
    ...(workspaceId ? { workspaceId } : {}),
  } as ChatSession & { workspaceId?: string };
}

export async function listInvestigations(database = db): Promise<ChatSession[]> {
  const [sessions, messages] = await Promise.all([
    database.chatSessions.toArray(),
    database.chatMessages.toArray(),
  ]);
  const bySession = new Map<string, ChatMessage[]>();
  for (const message of messages) {
    const items = bySession.get(message.sessionId) ?? [];
    items.push(message);
    bySession.set(message.sessionId, items);
  }
  // Legacy conversations are promoted lazily into named investigations.
  for (const [sessionId, sessionMessages] of bySession) {
    if (sessions.some((session) => session.id === sessionId)) continue;
    const first = [...sessionMessages].sort((a, b) => a.createdAt - b.createdAt)[0];
    if (!first) continue;
    sessions.push(createInvestigationSession(first.repositoryId ?? null, first.content.slice(0, 70) || 'Previous investigation'));
    sessions.at(-1)!.id = sessionId;
    sessions.at(-1)!.createdAt = first.createdAt;
  }
  return sessions.sort((a, b) => b.updatedAt - a.updatedAt);
}

export async function saveInvestigation(session: ChatSession, database = db): Promise<void> {
  await database.chatSessions.put({ ...session, updatedAt: Date.now() });
}

export async function deleteInvestigation(sessionId: string, database = db): Promise<void> {
  await database.transaction('rw', [database.chatSessions, database.chatMessages, database.investigationItems], async () => {
    await database.chatMessages.where('sessionId').equals(sessionId).delete();
    await database.investigationItems.where('sessionId').equals(sessionId).delete();
    await database.chatSessions.delete(sessionId);
  });
}

export async function addInvestigationItem(item: Omit<InvestigationItem, 'id' | 'createdAt' | 'updatedAt'>, database = db): Promise<InvestigationItem> {
  const now = Date.now();
  const value: InvestigationItem = { ...item, id: `item:${crypto.randomUUID()}`, createdAt: now, updatedAt: now };
  await database.investigationItems.put(value);
  return value;
}

export async function listInvestigationItems(sessionId: string, database = db): Promise<InvestigationItem[]> {
  return database.investigationItems.where('sessionId').equals(sessionId).sortBy('updatedAt');
}

export async function removeInvestigationItem(id: string, database = db): Promise<void> {
  await database.investigationItems.delete(id);
}

export async function createWorkspace(name: string, repositoryIds: string[], database = db): Promise<Workspace> {
  const now = Date.now();
  const workspace: Workspace = { id: `workspace:${crypto.randomUUID()}`, name: name.trim() || 'Untitled workspace', repositoryIds: [...new Set(repositoryIds)], createdAt: now, updatedAt: now };
  await database.workspaces.put(workspace);
  return workspace;
}

export async function deleteWorkspace(id: string, database = db): Promise<void> {
  await database.workspaces.delete(id);
}

export function generateInvestigationMarkdown(input: {
  session: ChatSession;
  repositories: Repository[];
  messages: ChatMessage[];
  items: InvestigationItem[];
}): string {
  const repoNames = new Map(input.repositories.map((repository) => [repository.id, `${repository.fullName}${repository.ref ? `@${repository.ref}` : ''}`]));
  const lines: string[] = [
    `# ${input.session.title}`,
    '',
    `> Generated by CodeContext on ${new Date().toISOString()}. Citations remain pinned to their source revision.`,
    '',
  ];
  if (input.items.length) {
    lines.push('## Pinned context', '');
    for (const item of input.items) {
      lines.push(`### ${item.title}`, '');
      if (item.filePath) lines.push(`Source: \`${item.filePath}${item.startLine ? `#L${item.startLine}${item.endLine && item.endLine > item.startLine ? `-L${item.endLine}` : ''}` : ''}\``, '');
      lines.push(item.content, '');
    }
  }
  lines.push('## Conversation', '');
  for (const message of [...input.messages].sort((a, b) => a.createdAt - b.createdAt)) {
    lines.push(`### ${message.role === 'user' ? 'Question' : 'CodeContext'}`, '', message.content, '');
    if (message.citations?.length) {
      lines.push('**Sources**', '');
      for (const citation of message.citations) {
        const label = `${repoNames.get(citation.repositoryId) ?? citation.repositoryId} · ${citation.filePath}#L${citation.startLine}-L${citation.endLine}`;
        lines.push(`- ${citation.githubUrl ? `[${label}](${citation.githubUrl})` : `\`${label}\``}`);
      }
      lines.push('');
    }
  }
  return lines.join('\n');
}

export function downloadTextFile(content: string, filename: string, type = 'text/markdown;charset=utf-8'): void {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename.replace(/[^a-z0-9_.-]+/gi, '-').slice(0, 120);
  anchor.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
